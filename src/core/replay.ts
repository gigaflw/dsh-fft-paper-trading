import { emptyState, applyEvent, verify } from './ledger.js'
import type { AccountState, LedgerEvent } from './types.js'

export interface ReplayResult {
  state: AccountState
  issues: string[]
}

/** Fold the event log into account state. Pure: no clock, no IO. */
export function replay(events: LedgerEvent[], accountId: string): ReplayResult {
  const state = emptyState(accountId)
  for (const event of events) {
    if (state.accountId !== accountId) state.accountId = accountId
    applyEvent(state, event)
  }
  return { state, issues: verify(state) }
}

export interface PreparedLedger {
  /** Events that survived duplicate collapsing, in file order. */
  events: LedgerEvent[]
  /** How many byte-equivalent repeats were dropped. */
  duplicates: number
  /** Sequence problems that are real corruption, not a repeated write. */
  issues: string[]
}

/**
 * Identity of one event for duplicate detection.
 *
 * The 5× write bug produced the same boundary event several times, generated by
 * concurrent reads that each read the clock: `payload.recordedAt` differs while
 * every account-affecting field is identical. Dropping the volatile stamp keeps
 * the repair honest — a repeat with a *different* equity/cash value is still a
 * conflict and must block instead of being repaired away.
 */
export function eventFingerprint(event: LedgerEvent): string {
  const payload = { ...(event.payload as Record<string, unknown>) }
  delete payload.recordedAt
  return JSON.stringify({ type: event.type, payload })
}

/**
 * Split a ledger into a replayable event list.
 *
 * Non-increasing seq is only tolerated when it repeats an already accepted
 * event with the same fingerprint; anything else is reported as an issue and
 * the loader keeps the original file (never destroying evidence).
 */
export function prepareLedger(events: readonly LedgerEvent[]): PreparedLedger {
  const kept: LedgerEvent[] = []
  const bySeq = new Map<number, LedgerEvent>()
  const issues: string[] = []
  let duplicates = 0
  for (const event of events) {
    if (!Number.isInteger(event.seq) || event.seq <= 0) {
      issues.push(`事件序号非法: ${String(event.seq)}`)
      continue
    }
    const last = kept[kept.length - 1]
    if (last === undefined || event.seq > last.seq) {
      kept.push(event)
      bySeq.set(event.seq, event)
      continue
    }
    const known = bySeq.get(event.seq)
    if (known !== undefined && eventFingerprint(known) === eventFingerprint(event)) {
      duplicates += 1
      continue
    }
    if (known !== undefined) issues.push(`事件序号重复且内容不同: ${event.seq}`)
    else issues.push(`事件序号不连续: ${last.seq} → ${event.seq}`)
  }
  return { events: kept, duplicates, issues }
}
